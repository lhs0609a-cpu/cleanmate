/**
 * 질문 설명 레이어 — "이게 뭔데요?"에 답한다
 *
 * hiberfil 프로브에는 7문답 설명이 있는데(types.ts의 Explanation), 정작
 * 질문 화면에는 없었다. "오랫동안 열지 않은 자료 316,511개(49.7GB)가 있어요.
 * 나중에 다시 볼 일 있으신가요?" 만 띄우고 답을 요구했다.
 *
 * 그건 우리가 비판하던 도구와 똑같다. 이 제품의 약속은 "뭘 지우는지 알고
 * 지웁니다"이고, 그 약속을 가장 크게 어기는 자리가 바로 질문 화면이었다.
 *
 * ── 규칙 ──────────────────────────────────────────────────────
 * 1) 손해를 먼저 쓴다. 좋은 점만 쓰면 광고다.
 * 2) 모르면 모른다고 쓴다. "안전합니다"라고 단정할 수 있는 건 규칙이
 *    확증한 것뿐이고, 질문으로 넘어온 건 정의상 확증 못 한 것들이다.
 * 3) 안 지운다는 선택지를 절대 뺏지 않는다.
 * 4) 숫자를 지어내지 않는다. 실제 집계(breakdown.ts)가 채운다.
 */

import type { Unknown } from '../types.ts'

export interface UnknownExplain {
  /** 이게 뭔가 — 전문용어 없이 */
  what: string
  /** 어디서 생겼나 */
  origin: string
  /** 지워도 되나 — 확신 수준을 숨기지 않는다 */
  safety: string
  /** 지우면 뭐가 달라지나. 손해를 먼저. */
  ifRemoved: string[]
  /** 되돌릴 수 있나 */
  recovery: string
  /** 안 지우면 */
  ifKept: string
}

